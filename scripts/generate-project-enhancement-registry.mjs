import fs from 'node:fs';
import path from 'node:path';

const groups = [
  ['project-media', 'mediaEntries', 'ProjectMediaData'],
  ['project-locations', 'locationEntries', 'ProjectLocationData'],
  ['project-floor-plans', 'floorPlanEntries', 'ProjectFloorPlanData'],
];
let code = '// Generated by scripts/generate-project-enhancement-registry.mjs. Only reviewed manifests belong in these folders.\n';
code += "import type { ProjectMediaData, ProjectLocationData, ProjectFloorPlanData } from '@/lib/project-enhancement-types';\n";
for (const [folder, collection, type] of groups) {
  const files = fs.readdirSync(`src/data/${folder}`, { recursive: true }).filter(file => String(file).endsWith('.json')).sort();
  const owners = new Set();
  for (const [index, file] of files.entries()) {
    const entry = JSON.parse(fs.readFileSync(path.join('src/data', folder, file), 'utf8'));
    if (!entry.projectId || !entry.projectSlug || !entry.developerSlug || owners.has(entry.projectId)) throw Error(`Invalid or repeated owner in ${folder}/${file}`);
    owners.add(entry.projectId);
    code += `import ${collection}${index} from '@/data/${folder}/${String(file).replaceAll('\\', '/')}' with { type: 'json' };\n`;
  }
  code += `export const ${collection}: readonly ${type}[] = [${files.map((_, i) => `${collection}${i}`).join(', ')}];\n`;
}
fs.writeFileSync('src/data/project-enhancement-registry.ts', code, 'utf8');
